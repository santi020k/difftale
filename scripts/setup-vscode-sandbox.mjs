import { spawnSync } from 'node:child_process'
import { chmod, mkdir, rm, stat, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sandboxRoot = join(repositoryRoot, '.difftale-sandbox')
const sandboxWorkspace = join(sandboxRoot, 'workspace')
const sandboxRemote = join(sandboxRoot, 'remote.git')
const resetRequested = process.argv.includes('--reset')

const pathExists = async path => {
  try {
    await stat(path)

    return true
  } catch (error) {
    if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
      return false
    }

    throw error
  }
}

const runGit = (arguments_, workingDirectory, environment = {}) => {
  const result = spawnSync('git', arguments_, {
    cwd: workingDirectory,
    encoding: 'utf8',
    env: {
      ...process.env,
      ...environment,
    },
  })

  if (result.status !== 0) {
    const detail = result.stderr.trim() || result.stdout.trim()

    throw new Error(`git ${arguments_.join(' ')} failed: ${detail}`)
  }
}

const writeWorkspaceFile = async (relativePath, contents) => {
  const targetPath = join(sandboxWorkspace, relativePath)

  await mkdir(dirname(targetPath), { recursive: true })

  await writeFile(targetPath, contents)
}

const commitEnvironment = sequence => ({
  GIT_AUTHOR_DATE: `2026-01-0${sequence}T12:00:00Z`,
  GIT_COMMITTER_DATE: `2026-01-0${sequence}T12:00:00Z`,
})

const createSandbox = async () => {
  if (resetRequested) {
    await rm(sandboxRoot, { force: true, recursive: true })
  }

  if (await pathExists(join(sandboxWorkspace, '.git'))) {
    console.log(`Difftale sandbox is ready at ${sandboxWorkspace}`)

    return
  }

  if (await pathExists(sandboxRoot)) {
    throw new Error(
      `The sandbox is incomplete. Run "pnpm sandbox:reset" to recreate ${sandboxRoot}.`,
    )
  }

  await mkdir(sandboxWorkspace, { recursive: true })

  await mkdir(sandboxRemote, { recursive: true })

  runGit(['init', '--bare', '--initial-branch=main'], sandboxRemote)

  runGit(['init', '--initial-branch=main'], sandboxWorkspace)

  runGit(['config', 'user.name', 'Difftale Sandbox'], sandboxWorkspace)

  runGit(['config', 'user.email', 'sandbox@difftale.local'], sandboxWorkspace)

  runGit(['config', 'core.hooksPath', '.githooks'], sandboxWorkspace)

  await writeWorkspaceFile(
    'README.md',
    `# Difftale Debug Sandbox

This disposable repository is generated by Difftale for Extension Development
Host testing. Commit, push, edit, rename, and delete files here freely.

Run \`pnpm sandbox:reset\` in the Difftale repository to restore this fixture.
`,
  )

  await writeWorkspaceFile(
    'src/story.ts',
    `export const opening = 'Once upon a commit'
`,
  )

  await writeWorkspaceFile(
    '.githooks/pre-commit',
    `#!/bin/sh
echo "[difftale sandbox] pre-commit hook passed"
`,
  )

  await writeWorkspaceFile(
    '.githooks/pre-push',
    `#!/bin/sh
echo "[difftale sandbox] pre-push hook passed"
`,
  )

  await chmod(join(sandboxWorkspace, '.githooks/pre-commit'), 0o755)

  await chmod(join(sandboxWorkspace, '.githooks/pre-push'), 0o755)

  runGit(['add', '.'], sandboxWorkspace)

  runGit(
    ['commit', '-m', 'chore: create sandbox story'],
    sandboxWorkspace,
    commitEnvironment(1),
  )

  await writeWorkspaceFile(
    'src/story.ts',
    `export const opening = 'Once upon a commit'

export const ending = 'The history remains readable'
`,
  )

  runGit(['add', 'src/story.ts'], sandboxWorkspace)

  runGit(
    ['commit', '-m', 'feat(story): add an ending'],
    sandboxWorkspace,
    commitEnvironment(2),
  )

  runGit(['mv', 'src/story.ts', 'src/tale.ts'], sandboxWorkspace)

  runGit(
    ['commit', '-m', 'refactor(story): rename story as tale'],
    sandboxWorkspace,
    commitEnvironment(3),
  )

  runGit(['remote', 'add', 'origin', sandboxRemote], sandboxWorkspace)

  runGit(['push', '--set-upstream', 'origin', 'main'], sandboxWorkspace)

  runGit(['switch', '-c', 'sandbox-changes'], sandboxWorkspace)

  await writeWorkspaceFile(
    'src/tale.ts',
    `export const opening = 'Once upon a commit'

export const middle = 'A feature branch appeared'

export const ending = 'The history remains readable'
`,
  )

  runGit(['add', 'src/tale.ts'], sandboxWorkspace)

  runGit(
    ['commit', '-m', 'feat(story): add a middle chapter'],
    sandboxWorkspace,
    commitEnvironment(4),
  )

  await writeWorkspaceFile(
    'src/draft.ts',
    `export const draft = 'This staged file is ready for commit generation'
`,
  )

  runGit(['add', 'src/draft.ts'], sandboxWorkspace)

  await writeWorkspaceFile(
    'src/tale.ts',
    `export const opening = 'Once upon a commit'

export const middle = 'A feature branch appeared'

export const ending = 'The history remains readable'

export const epilogue = 'This unstaged line exercises working-tree history'
`,
  )

  await writeWorkspaceFile(
    'notes.md',
    `# Untracked notes

Use this file to exercise Source Control actions without touching the real
Difftale repository.
`,
  )

  console.log(`Created Difftale sandbox at ${sandboxWorkspace}`)
}

await createSandbox()
